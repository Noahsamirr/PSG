function exitName(r: string) {
  return r === 'SL' ? 'ضُرب الوقف' : r === 'BE' ? 'خروج عند التعادل' : r === 'Trail' ? 'وقف متحرك' : r === 'Rule exit' ? 'قاعدة خروج' : r === 'Opposite signal' ? 'إشارة معاكسة' : r === 'Time exit' ? 'خروج زمني' : /^TP\d$/.test(r) ? `الهدف ${r.slice(2)}` : r;
}

